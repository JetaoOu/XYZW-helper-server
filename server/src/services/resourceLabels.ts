/** 把归一化后的奖励映射转成可读文本 */
export function formatGainText(gain: Record<string, number>): string {
  return Object.entries(gain)
    .filter(([, value]) => value !== 0)
    .map(([key, value]) => {
      if (key === "gold") return `金币x${value}`;
      if (key === "diamond") return `金砖x${value}`;
      if (key.startsWith("item:")) {
        const id = Number(key.slice(5));
        return `${RESOURCE_LABELS[id] ?? `物品${id}`}x${value}`;
      }
      return `${key}x${value}`;
    })
    .join("，");
}
